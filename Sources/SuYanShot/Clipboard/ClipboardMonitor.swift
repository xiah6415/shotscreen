import AppKit

/// Polls the general pasteboard (macOS has no change notification) and reports new copies.
/// Skips content that apps mark as secret or temporary, and anything copied from password managers.
@MainActor
final class ClipboardMonitor {
    var onCapture: ((ClipboardSnapshot) -> Void)?

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var ignoredChangeCount: Int?

    /// nspasteboard.org markers used by password managers and clipboard-aware apps.
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword")
    ]
    private static let skippedApps: Set<String> = [
        "com.apple.keychainaccess", "com.apple.Passwords",
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop"
    ]
    /// Larger text is skipped rather than bloating the history.
    private static let maxTextLength = 1_000_000

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Our own write when pasting from history must not be recorded as a new copy.
    func ignore(changeCount: Int) { ignoredChangeCount = changeCount }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard pasteboard.changeCount != ignoredChangeCount else { return }

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.skippedTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication
        if let bundleID = source?.bundleIdentifier, Self.skippedApps.contains(bundleID) { return }
        let ownApp = source?.processIdentifier == ProcessInfo.processInfo.processIdentifier
        let sourceName = ownApp ? "素顏 Shot" : source?.localizedName
        let sourceID = ownApp ? Bundle.main.bundleIdentifier : source?.bundleIdentifier

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            onCapture?(ClipboardSnapshot(kind: .file, fileURLs: urls, sourceAppName: sourceName, sourceBundleID: sourceID))
            return
        }

        if types.contains(.png) || types.contains(.tiff) {
            let png = pasteboard.data(forType: .png)
            let tiff = png == nil ? pasteboard.data(forType: .tiff) : nil
            // TIFF from screenshots can be tens of MB; convert to PNG off the main thread.
            Task { @MainActor [weak self] in
                let converted = await Task.detached(priority: .utility) { () -> (Data, CGSize)? in
                    guard let data = png ?? tiff, let rep = NSBitmapImageRep(data: data) else { return nil }
                    let size = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
                    if png != nil { return (data, size) }
                    return rep.representation(using: .png, properties: [:]).map { ($0, size) }
                }.value
                guard let (data, size) = converted else { return }
                self?.onCapture?(ClipboardSnapshot(kind: .image, png: data, imagePixelSize: size, sourceAppName: sourceName, sourceBundleID: sourceID))
            }
            return
        }

        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maxTextLength else { return }
        let rtf = pasteboard.data(forType: .rtf)
        let html = pasteboard.data(forType: .html)
        onCapture?(ClipboardSnapshot(kind: rtf != nil || html != nil ? .richText : .text, text: text, rtf: rtf, html: html,
                                     sourceAppName: sourceName, sourceBundleID: sourceID))
    }
}
